describe('simple block problems', () => {
  it('report a port used for two kinds of device', () => {
    const { problems } = generate(
      program([
        { type: 'mp_motor_start', fields: { PORT: 'C', DIRECTION: 'CLOCKWISE' } },
        {
          type: 'mp_print',
          inputs: {
            VALUE: reporter({
              type: 'mp_sensor_reflection',
              id: 'colour-on-c',
              fields: { PORT: 'C' },
            }),
          },
        },
      ]),
    );
    expect(problems).toEqual([
      {
        blockId: 'colour-on-c',
        message: 'Port C is used for a motor in another block. One port holds one device.',
      },
    ]);
  });

  it('report a port the “set up” block already uses', () => {
    const { problems } = generate(
      program(
        [{ type: 'mp_motor_stop_simple', id: 'simple-a', fields: { PORT: 'A' } }],
        [
          {
            type: 'mp_setup',
            inputs: {
              DEVICES: {
                block: {
                  type: 'mp_setup_motor',
                  fields: { VAR: { id: 'm1' }, PORT: 'A', DIRECTION: 'CLOCKWISE' },
                },
              },
            },
          },
        ],
        [{ name: 'arm', id: 'm1', type: 'Motor' }],
      ),
    );
    expect(problems).toEqual([
      {
        blockId: 'simple-a',
        message:
          'Port A is set up as “arm” in the “set up” block. Use the “arm” blocks, or choose another port.',
      },
    ]);
  });

  it('report movement motors on a port the “set up” block uses', () => {
    const { problems } = generate(
      program(
        [
          { type: 'mp_move_motors', id: 'wheels', fields: { PORTS: 'CD' } },
          { type: 'mp_move_stop' },
        ],
        [
          {
            type: 'mp_setup',
            inputs: {
              DEVICES: {
                block: { type: 'mp_setup_color_sensor', fields: { VAR: { id: 'c1' }, PORT: 'D' } },
              },
            },
          },
        ],
        [{ name: 'floor', id: 'c1', type: 'ColorSensor' }],
      ),
    );
    expect(problems).toEqual([
      {
        blockId: 'wheels',
        message:
          'Port D is set up as “floor”, so it cannot also drive the right wheel. Choose other movement motors.',
      },
    ]);
  });

  it('report movement settings that disagree, but not ones that repeat', () => {
    const { problems } = generate(
      program([
        { type: 'mp_move_motors', fields: { PORTS: 'AB' } },
        { type: 'mp_move_motors', fields: { PORTS: 'AB' } },
        { type: 'mp_move_motors', id: 'second', fields: { PORTS: 'CD' } },
        { type: 'mp_move_wheels', fields: { WHEEL: 56, TRACK: 112 } },
        { type: 'mp_move_wheels', id: 'wheels', fields: { WHEEL: 88, TRACK: 112 } },
        { type: 'mp_move_stop' },
      ]),
    );
    expect(problems.map((problem) => problem.blockId)).toEqual(['second', 'wheels']);
  });

  it('do not create a drive base for settings alone', () => {
    const { code, problems } = generate(
      program([{ type: 'mp_move_motors', fields: { PORTS: 'AB' } }]),
    );
    expect(problems).toEqual([]);
    expect(code).not.toContain('DriveBase');
  });
});

describe('number folding', () => {
  it('folds literals and wraps expressions', () => {
    expect(literal('12')).toBe(12);
    expect(literal('-0.5')).toBe(-0.5);
    expect(literal('x')).toBeNull();
    expect(negated('90')).toBe('-90');
    expect(negated('-90')).toBe('90');
    expect(negated('x + 1')).toBe('-(x + 1)');
    expect(scaled('0.1', 3)).toBe('0.3');
    expect(scaled('1.5', 1000)).toBe('1500');
    expect(scaled('x', 360)).toBe('x * 360');
    expect(formatNumber(0.1 + 0.2)).toBe('0.3');
  });
});
