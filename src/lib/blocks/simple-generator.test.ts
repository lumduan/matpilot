import { loadWorkspace, registerBlocks } from './register';

type State = Record<string, unknown>;

const num = (value: number) => ({ shadow: { type: 'math_number', fields: { NUM: value } } });
const text = (value: string) => ({ shadow: { type: 'text', fields: { TEXT: value } } });
const turn = (value: number) => ({ shadow: { type: 'mp_turn_angle', fields: { ANGLE: value } } });
const steering = (value: number) => ({
  shadow: { type: 'mp_steering', fields: { STEERING: value } },
});
const percent = (value: number) => ({
  shadow: { type: 'mp_percent', fields: { PERCENT: value } },
});
const reporter = (block: State, fallback = num(0)) => ({ ...fallback, block });

function chain(blocks: State[]): State | undefined {
  return blocks.reduceRight<State | undefined>(
    (next, block) => (next ? { ...block, next: { block: next } } : block),
    undefined,
  );
}

/** A workspace with only the program block (and, optionally, a "set up" block). */
function program(blocks: State[], extra: State[] = [], variables: State[] = []): State {
  const body = chain(blocks);
  return {
    variables,
    blocks: {
      languageVersion: 0,
      blocks: [
        { type: 'mp_program', x: 0, y: 0, ...(body ? { next: { block: body } } : {}) },
        ...extra,
      ],
    },
  };
}

function generate(state: State) {
  const workspace = new Blockly.Workspace();
  try {
    loadWorkspace(workspace, state);
    return generateProgram(workspace);
  } finally {
    workspace.dispose();
  }
}

async function expectCompiles(code: string) {
  const outcome = await compilePython(code);
  expect(
    outcome.ok,
    outcome.ok ? '' : `${outcome.error.message} (line ${outcome.error.line})\n${code}`,
  ).toBe(true);
}

