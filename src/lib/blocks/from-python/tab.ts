/** A range of the text the user may change. */
export interface TextRange {
  readonly from: number;
  readonly to: number;
}

export interface PythonEdit {
  readonly tabId: string;
  /** `main.py`, or the tab's name and `.py`. */
  readonly fileName: string;
  readonly text: string;
  /** The parts the user may change; the rest is made from the blocks. */
  readonly editable: readonly TextRange[];
  /** This program's names, for the editor's suggestions (./vocabulary.ts). */
  readonly names: ProgramNames;
}

const FUNCTIONS = 'Functions';
const MAIN = 'Main';
const RULE = /^# --- ([A-Za-z ]+?) -+$/;

/** Where each section heading is: its title, and where its line starts and ends. */
function headings(text: string): { title: string; from: number; to: number }[] {
  const out: { title: string; from: number; to: number }[] = [];
  let from = 0;
  for (const line of text.split('\n')) {
    const match = RULE.exec(line);
    if (match && line === rule(match[1]!))
      out.push({ title: match[1]!, from, to: from + line.length });
    from += line.length + 1;
  }
  return out;
}

/** The parts of a file the user may change (see the module comment). */
export function editableRanges(text: string, isMain: boolean): TextRange[] {
  const marks = headings(text);
  const ranges: TextRange[] = [];
  const end = (index: number) => marks[index + 1]?.from ?? text.length;
  for (const [index, mark] of marks.entries()) {
    const start = Math.min(text.length, mark.to + 1);
    if (mark.title === FUNCTIONS) ranges.push({ from: start, to: end(index) });
    if (mark.title === MAIN && isMain) {
      const stop = end(index);
      const body = text.slice(start, stop);
      if (body.startsWith('try:\n')) {
        const finallyAt = body.lastIndexOf('\nfinally:');
        ranges.push({
          from: start + 'try:\n'.length,
          to: finallyAt >= 0 ? start + finallyAt + 1 : stop,
        });
      } else {
        ranges.push({ from: start, to: stop });
      }
    }
  }
  return ranges;
}

/** The tab's file for editing, with an empty Functions section to type into if it has none. */
export function pythonForEditing(tabs: readonly ProgramTab[], tabId: string): PythonEdit {
  registerBlocks();
  const tab = tabs.find((each) => each.id === tabId);
  if (!tab) throw new Error(`No tab ${tabId}.`);
  const isMain = tab === tabs[0];
  const program = generateTabs(tabs);
  const file = program.files.find((each) => each.tabId === tabId);
  const fileName = isMain ? 'main.py' : `${tab.name}.py`;
  let text = file?.code ?? `# Generated by MatPilot from blocks: the tab “${tab.name}”.\n`;
  if (!headings(text).some((mark) => mark.title === FUNCTIONS)) {
    const section = `${rule(FUNCTIONS)}\n\n\n`;
    const main = headings(text).find((mark) => mark.title === MAIN);
    text = main
      ? `${text.slice(0, main.from)}${section}${text.slice(main.from)}`
      : `${text.trimEnd()}\n\n${section}`;
  }
  return {
    tabId,
    fileName,
    text,
    editable: editableRanges(text, isMain),
    names: programNames(tabs, tab),
  };
}

/** The names the tab's Python may use: its variables, shared ones, devices, functions, tabs. */
export function programNames(tabs: readonly ProgramTab[], tab: ProgramTab): ProgramNames {
  const main = tabs[0]!;
  const shared: string[] = [];
  for (const [name, variable] of pythonNames(main.workspace)) {
    if (variable.getType() === SHARED_VARIABLE_TYPE) shared.push(name);
  }
  const variables: string[] = [];
  const devices: { name: string; type: DeviceType }[] = [];
  for (const [name, variable] of pythonNames(tab.workspace)) {
    const type = variable.getType();
    if (isDeviceType(type)) devices.push({ name, type });
    else if (type === '') variables.push(name);
  }
  const functions: { name: string; inputs: string[]; tab: string | null }[] = [];
  const modules = new Set<string>();
  for (const info of collectFunctions(tabs).values()) {
    if (!info.enabled) continue;
    const inputs = info.inputs.map((input) => input.name);
    if (info.tab === tab) functions.push({ name: info.name, inputs, tab: null });
    else if (info.tab !== main) {
      functions.push({ name: info.name, inputs, tab: info.tab.name });
      modules.add(info.tab.name);
    }
  }
  return { variables, shared, devices, functions, tabs: [...modules] };
}

export interface PythonRead {
  readonly problems: readonly PythonProblem[];
  /** The tab's new saved state (Blockly's workspace JSON), when there are no problems. */
  readonly state: object | null;
  /** Define blocks that are new, with no place yet: the editor puts them below the others. */
  readonly unplaced: readonly string[];
  /** Blocks that were turned off in the replaced code: the Python leaves them out. */
  readonly droppedDisabled: number;
}

type VariableState = { name: string; id: string; type?: string };

/** `type` and `type|FIELD=value,...` for each block: which kinds the tab used. */
function signatures(workspace: Blockly.Workspace): Set<string> {
  const out = new Set<string>();
  for (const block of workspace.getAllBlocks(false)) {
    const fields: string[] = [];
    for (const input of block.inputList) {
      for (const field of input.fieldRow) {
        const value: unknown = field.getValue();
        if (
          field.name &&
          !(field instanceof Blockly.FieldVariable) &&
          (typeof value === 'string' || typeof value === 'number')
        ) {
          fields.push(`${field.name}=${String(value)}`);
        }
      }
    }
    out.add(block.type);
    out.add(`${block.type}|${fields.sort().join(',')}`);
  }
  return out;
}

/** Python names of a workspace's variables, as the generator gives them. */
function pythonNames(
  workspace: Blockly.Workspace,
): Map<string, Blockly.IVariableModel<Blockly.IVariableState>> {
  pythonGenerator.init(workspace);
  const out = new Map<string, Blockly.IVariableModel<Blockly.IVariableState>>();
  for (const variable of workspace.getVariableMap().getAllVariables()) {
    out.set(pythonGenerator.getVariableName(variable.getId()), variable);
  }
  return out;
}

/** The `#` comments inside these spans, in order (section headings are not comments). */
function editableComments(
  tree: Tree,
  source: Source,
  spans: readonly ({ from: number; to: number } | null | undefined)[],
): SyntaxNode[] {
  const inside = spans.filter((span): span is { from: number; to: number } => !!span);
  const out: SyntaxNode[] = [];
  tree.iterate({
    enter(node) {
      if (node.name !== 'Comment') return;
      const text = source.of(node.node);
      const heading = RULE.exec(text);
      if (heading && text === rule(heading[1]!)) return;
      if (inside.some((span) => node.from >= span.from && node.from < span.to)) out.push(node.node);
    },
  });
  return out;
}

/** Names assigned anywhere in these statements (`x = ...`, `x += ...`). */
function assignedNames(source: Source, nodes: readonly SyntaxNode[]): Set<string> {
  const out = new Set<string>();
  for (const node of nodes) {
    const cursor = node.cursor();
    do {
      if (cursor.name === 'AssignStatement' || cursor.name === 'UpdateStatement') {
        const target = cursor.node.firstChild;
        if (target?.name === 'VariableName') out.add(source.of(target));
      }
    } while (cursor.next() && cursor.from < node.to);
  }
  return out;
}

export function readTabPython(
  tabs: readonly ProgramTab[],
  tabId: string,
  text: string,
): PythonRead {
  registerBlocks();
  const failed = (problems: readonly PythonProblem[]): PythonRead => ({
    problems,
    state: null,
    unplaced: [],
    droppedDisabled: 0,
  });
  const tab = tabs.find((each) => each.id === tabId);
  const main = tabs[0];
  if (!tab || !main) return failed([{ from: 0, to: 0, message: 'This tab is gone.' }]);
  const isMain = tab === main;
  const source = new Source(text);
  const { tree, problems: syntax } = parsePython(text);
  if (syntax.length > 0) return failed(syntax);

  // --- Sections: the statements under "Functions" and "Main" --------------------------------
  const problems: PythonProblem[] = [];
  const definitions: SyntaxNode[] = [];
  let program: SyntaxNode[] = [];
  let section = '';
  // Where the Functions part and main's program are, for their comments.
  const spans = new Map<string, { from: number; to: number }>();
  let mainBody: { from: number; to: number } | null = null;
  for (let node = tree.topNode.firstChild; node; node = node.nextSibling) {
    if (node.name === 'Comment') {
      const match = RULE.exec(source.of(node));
      if (match && source.of(node) === rule(match[1]!)) {
        const open = spans.get(section);
        if (open) spans.set(section, { from: open.from, to: node.from });
        section = match[1]!;
        spans.set(section, { from: node.to, to: text.length });
      }
      continue;
    }
    if (section === FUNCTIONS) {
      if (node.name === 'FunctionDefinition') definitions.push(node);
      else
        problems.push({
          from: node.from,
          to: node.to,
          message: 'Only functions (def …) go in the “Functions” part. Put this under Main.',
        });
    } else if (section === MAIN && isMain) {
      const finallyWord =
        node.name === 'TryStatement' ? parts(node).find((part) => part.name === 'finally') : null;
      if (node.name === 'TryStatement' && finallyWord && program.length === 0) {
        const body = node.getChild('Body')!;
        mainBody = { from: body.from, to: body.to };
        program = statements(body);
      } else {
        program.push(node);
      }
    }
  }
  program = program.filter((node) => node.name !== 'PassStatement');

  // --- Names ---------------------------------------------------------------------------------
  const mainNames = pythonNames(main.workspace);
  const shared = new Map<string, string>();
  for (const [name, variable] of mainNames) {
    if (variable.getType() === SHARED_VARIABLE_TYPE) shared.set(name, variable.getId());
  }
  const tabNames = pythonNames(tab.workspace);
  const devices = new Map<string, { id: string; type: DeviceType }>();
  const variables = new Map<string, string>();
  for (const [name, variable] of tabNames) {
    const type = variable.getType();
    if (isDeviceType(type)) devices.set(name, { id: variable.getId(), type });
    else if (type === '') variables.set(name, variable.getId());
  }

  // --- Functions -----------------------------------------------------------------------------
  const all = collectFunctions(tabs);
  const oldOwn = new Map(
    [...all.values()].filter((info) => info.tab === tab).map((info) => [info.name, info]),
  );
  const otherFunctions = new Map<string, Map<string, FunctionRef>>();
  const mainFunctions = new Set<string>();
  const takenElsewhere = new Map<string, string>();
  for (const info of all.values()) {
    if (info.tab === tab) continue;
    takenElsewhere.set(info.name, info.tab.name);
    if (info.tab === main) {
      mainFunctions.add(info.name);
      continue;
    }
    const byName = otherFunctions.get(info.tab.name) ?? new Map<string, FunctionRef>();
    byName.set(info.name, { id: info.id, name: info.name, inputs: info.inputs });
    otherFunctions.set(info.tab.name, byName);
  }
  const tabModuleNames = tabs.map((each) => each.name);
  const ownFunctions = new Map<string, FunctionRef>();
  const refs = new Map<SyntaxNode, FunctionRef>();
  for (const node of definitions) {
    const nameNode = node.getChild('VariableName');
    const params = node.getChild('ParamList');
    if (!nameNode || !params) {
      problems.push({ from: node.from, to: node.to, message: 'A function is def name(inputs):.' });
      continue;
    }
    const name = source.of(nameNode);
    const where = { from: nameNode.from, to: nameNode.to };
    if (!PYTHON_NAME.test(name) || name.length > FUNCTION_NAME_MAX_LENGTH) {
      problems.push({
        ...where,
        message: `A function name starts with a letter, then letters, numbers or _, at most ${FUNCTION_NAME_MAX_LENGTH} characters.`,
      });
      continue;
    }
    if (isReservedName(name) || tabModuleNames.includes(name) || devices.has(name)) {
      problems.push({
        ...where,
        message: `“${name}” is already a name the program uses. Choose another name.`,
      });
      continue;
    }
    if (takenElsewhere.has(name)) {
      problems.push({
        ...where,
        message: `The tab “${takenElsewhere.get(name)}” already has a function “${name}”.`,
      });
      continue;
    }
    if (ownFunctions.has(name)) {
      problems.push({ ...where, message: `There are two functions called “${name}”.` });
      continue;
    }
    const inputNames: string[] = [];
    for (const param of parts(params)) {
      const paramName = source.of(param);
      if (param.name !== 'VariableName') {
        problems.push({
          from: param.from,
          to: param.to,
          message: 'Function inputs are names only, without default values.',
        });
      } else if (
        !PYTHON_NAME.test(paramName) ||
        paramName.length > INPUT_NAME_MAX_LENGTH ||
        isReservedName(paramName)
      ) {
        problems.push({
          from: param.from,
          to: param.to,
          message: `“${paramName}” cannot be an input name. Choose another name.`,
        });
      } else if (inputNames.includes(paramName)) {
        problems.push({
          from: param.from,
          to: param.to,
          message: `Two inputs are called “${paramName}”.`,
        });
      } else {
        inputNames.push(paramName);
      }
    }
    if (inputNames.length > MAX_FUNCTION_INPUTS) {
      problems.push({
        from: params.from,
        to: params.to,
        message: `A function has at most ${MAX_FUNCTION_INPUTS} inputs.`,
      });
    }
    const old = oldOwn.get(name);
    const ref: FunctionRef = {
      id: old?.id ?? newId(),
      name,
      inputs: inputNames.map((input) => ({
        id: old?.inputs.find((each) => each.name === input)?.id ?? newId(),
        name: input,
      })),
    };
    ownFunctions.set(name, ref);
    refs.set(node, ref);
  }

  // --- Read ----------------------------------------------------------------------------------
  const reserved = new Set<string>([
    ...tabModuleNames,
    ...takenElsewhere.keys(),
    ...ownFunctions.keys(),
  ]);
  const context: ReaderContext = {
    source,
    devices,
    variables,
    shared,
    ownFunctions,
    otherFunctions,
    mainFunctions: isMain ? new Set() : mainFunctions,
    isReserved: (name) => reserved.has(name) || isReservedName(name),
    assigned: assignedNames(source, [...definitions, ...program]),
    signatures: signatures(tab.workspace),
    comments: editableComments(tree, source, [
      spans.get(FUNCTIONS),
      isMain ? (mainBody ?? spans.get(MAIN)) : undefined,
    ]),
  };
  const reader = new Reader(context);
  const readable = definitions.filter((node) => refs.has(node));
  const defines = readable.map((node) => reader.define(node, refs.get(node)!));
  // The functions' comments: those above a def go to its block.
  reader.placeComments(readable, defines, spans.get(FUNCTIONS) ?? null);
  const functionOrphans = reader.orphans;
  const mainBlocks = isMain ? reader.body(program, mainBody ?? spans.get(MAIN) ?? null) : [];
  const programComments = isMain ? [...functionOrphans, ...reader.orphans] : [];
  problems.push(...reader.problems);
  if (problems.length > 0) return failed(problems.sort((a, b) => a.from - b.from));

  // --- The tab's new state -------------------------------------------------------------------
  const old = Blockly.serialization.workspaces.save(tab.workspace) as {
    blocks?: { languageVersion: number; blocks: BlockState[] };
    variables?: VariableState[];
  };
  const roots = [
    ...(isMain ? tab.workspace.getBlocksByType('mp_program', true).slice(0, 1) : []),
    ...tab.workspace.getBlocksByType(FUNCTION_BLOCKS.define, false),
  ];
  const silent: BlockState[] = [];
  let droppedDisabled = 0;
  for (const root of roots) {
    for (const block of root.getDescendants(true)) {
      if (block !== root && !block.isEnabled()) droppedDisabled += 1;
      if (SILENT_BLOCKS.has(block.type)) {
        const state = Blockly.serialization.blocks.save(block, {
          addCoordinates: false,
          addNextBlocks: false,
        });
        if (state) silent.push(state);
      }
    }
  }
  const oldDefines = new Map(
    (old.blocks?.blocks ?? [])
      .filter((state) => state.type === FUNCTION_BLOCKS.define)
      .map((state) => [
        String((state.fields as Record<string, unknown> | undefined)?.NAME ?? ''),
        state,
      ]),
  );
  const programId = roots[0]?.type === 'mp_program' ? roots[0].id : null;
  const kept = (old.blocks?.blocks ?? []).filter((state) => state.type !== FUNCTION_BLOCKS.define);
  const tops: BlockState[] = [];
  let silentPlaced = !silent.length;
  for (const state of kept) {
    if (isMain && state.id === programId) {
      const next = chain([...silent, ...mainBlocks]);
      const { next: _old, icons: _icons, ...rest } = state;
      void _old;
      void _icons;
      // Comments under Main that no block took stay on "when the program starts".
      const program: BlockState = next ? { ...rest, next: { block: next } } : rest;
      addComment(program, programComments);
      tops.push(program);
      silentPlaced = true;
    } else {
      tops.push(state);
    }
  }
  if (isMain && programId === null) {
    const next = chain([...silent, ...mainBlocks]);
    tops.unshift({ type: 'mp_program', x: 24, y: 24, ...(next ? { next: { block: next } } : {}) });
    silentPlaced = true;
  }
  const unplaced: string[] = [];
  for (const define of defines) {
    const name = String((define.fields as Record<string, unknown>).NAME);
    const before = oldDefines.get(name);
    let state = define;
    if (!silentPlaced) {
      // Outside main, settings blocks go first in the first function, where they still count.
      const body = (state.inputs as Record<string, { block?: BlockState }> | undefined)?.DO?.block;
      const first = chain([...silent, ...(body ? flatten(body) : [])]);
      state = {
        ...state,
        inputs: { ...(state.inputs ?? {}), ...(first ? { DO: { block: first } } : {}) },
      };
      silentPlaced = true;
    }
    if (before && typeof before.x === 'number' && typeof before.y === 'number') {
      tops.push({ ...state, x: before.x, y: before.y });
    } else {
      tops.push({ ...state, x: 24, y: 24 });
      unplaced.push(state.id!);
    }
  }
  if (!silentPlaced) {
    const stack = chain(silent);
    if (stack) tops.push({ ...stack, x: 24, y: 24 });
  }
  const variablesState: VariableState[] = [
    ...(old.variables ?? []),
    ...[...reader.newVariables].map(([name, id]) => ({ name, id, type: '' })),
  ];
  const state = {
    ...old,
    blocks: { languageVersion: old.blocks?.languageVersion ?? 0, blocks: tops },
    ...(variablesState.length > 0 ? { variables: variablesState } : {}),
  };

  // Make sure Blockly can load it before anything is replaced.
  const check = new Blockly.Workspace();
  try {
    Blockly.Events.disable();
    Blockly.serialization.workspaces.load(state, check);
  } catch (error) {
    return failed([
      {
        from: 0,
        to: Math.min(1, text.length),
        message: `MatPilot could not make blocks from this: ${error instanceof Error ? error.message : String(error)}`,
      },
    ]);
  } finally {
    Blockly.Events.enable();
    check.dispose();
  }
  return { problems: [], state, unplaced, droppedDisabled };
}

/** A chain as a list (the `next` links taken apart). */
function flatten(first: BlockState): BlockState[] {
  const out: BlockState[] = [];
  let current: BlockState | undefined = first;
  while (current) {
    const following: BlockState | undefined = current.next?.block;
    const rest: BlockState = { ...current };
    delete rest.next;
    out.push(rest);
    current = following;
  }
  return out;
}
