/**
 * Editing a tab's Python on the Blocks page (ADR 0014).
 *
 * `pythonForEditing` gives the tab's file as the generator writes it, with the parts the user may
 * change: the Functions section and, in main, the program under Main. Everything else (imports,
 * Config, Setup, Helpers, Variables) comes from the blocks and the devices, and stays as it is.
 *
 * `readTabPython` turns that text back into the tab's blocks: the functions and main's program
 * are replaced; the "set up" block, loose blocks, and blocks that only change the Config are
 * kept. It changes nothing itself: it returns the problems, or the tab's new saved state.
 */
