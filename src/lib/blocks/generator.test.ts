describe('problems', () => {
  it('reports a device that is used but not set up, on the block that uses it', () => {
    const { problems } = generate(
      workspaceState(
        [setupBlock('mp_setup_motor', 'm1', 'A', { DIRECTION: 'CLOCKWISE' })],
        [{ type: 'mp_motor_run', id: 'run-right', fields: motor('m2'), inputs: { SPEED: num(1) } }],
      ),
    );
    expect(problems).toEqual([
      {
        blockId: 'run-right',
        tabId: 'main',
        message: '“right motor” is not set up. Add a motor for it in the “set up” block.',
      },
    ]);
  });

  it('reports two devices on one port, and a device set up twice', () => {
    const { problems } = generate(
      workspaceState(
        [
          setupBlock('mp_setup_motor', 'm1', 'A', { DIRECTION: 'CLOCKWISE' }),
          { ...setupBlock('mp_setup_color_sensor', 'c1', 'A'), id: 'colour-on-a' },
          { ...setupBlock('mp_setup_motor', 'm1', 'C', { DIRECTION: 'CLOCKWISE' }), id: 'twice' },
        ],
        [],
      ),
    );
    expect(problems).toEqual([
      {
        blockId: 'colour-on-a',
        tabId: 'main',
        message: 'Port A is already used by “left motor”. Choose another port.',
      },
      {
        blockId: 'twice',
        tabId: 'main',
        message: '“left motor” is set up twice. Remove one of the two set-up blocks.',
      },
    ]);
  });

  it('adds the program block, and only that, to an empty saved workspace', () => {
    const workspace = new Blockly.Workspace();
    loadWorkspace(workspace, {});
    expect(workspace.getBlocksByType('mp_setup', false)).toHaveLength(0);
    const [program] = workspace.getBlocksByType('mp_program', false);
    expect(program?.isDeletable()).toBe(false);
    expect(generateProgram(workspace).problems).toEqual([]);
    workspace.dispose();
  });

  it('lets an older saved “set up” block be deleted', () => {
    const workspace = new Blockly.Workspace();
    loadWorkspace(workspace, {
      blocks: { languageVersion: 0, blocks: [{ type: 'mp_setup', deletable: false }] },
    });
    expect(workspace.getBlocksByType('mp_setup', false)[0]?.isDeletable()).toBe(true);
    workspace.dispose();
  });
});

describe('listSetUpDevices', () => {
  it('lists the set-up devices in order with their ports', () => {
    const workspace = new Blockly.Workspace();
    loadWorkspace(workspace, workspaceState(ALL_DEVICES, []));
    expect(listSetUpDevices(workspace).map((d) => `${d.name}@${d.port}`)).toEqual([
      'left motor@A',
      'right motor@B',
      'colour sensor@D',
      'distance sensor@E',
      'touch sensor@F',
    ]);
    workspace.dispose();
  });
});

