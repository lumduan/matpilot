type State = Record<string, unknown>;

const num = (value: number) => ({ shadow: { type: 'math_number', fields: { NUM: value } } });
const text = (value: string) => ({ shadow: { type: 'text', fields: { TEXT: value } } });
const input = (block: State) => ({ block });
const motor = (id: string) => ({ MOTOR: { id } });
const sensor = (id: string) => ({ SENSOR: { id } });

/** Links statement blocks into one stack through their `next` connections. */
function chain(blocks: State[]): State | undefined {
  return blocks.reduceRight<State | undefined>(
    (next, block) => (next ? { ...block, next: { block: next } } : block),
    undefined,
  );
}

const DEVICE_VARIABLES = [
  { name: 'left motor', id: 'm1', type: 'Motor' },
  { name: 'right motor', id: 'm2', type: 'Motor' },
  { name: 'colour sensor', id: 'c1', type: 'ColorSensor' },
  { name: 'distance sensor', id: 'u1', type: 'UltrasonicSensor' },
  { name: 'touch sensor', id: 'f1', type: 'ForceSensor' },
];

const setupBlock = (type: string, id: string, port: string, extra: State = {}) => ({
  type,
  fields: { VAR: { id }, PORT: port, ...extra },
});

const ALL_DEVICES = [
  setupBlock('mp_setup_motor', 'm1', 'A', { DIRECTION: 'CLOCKWISE' }),
  setupBlock('mp_setup_motor', 'm2', 'B', { DIRECTION: 'COUNTERCLOCKWISE' }),
  setupBlock('mp_setup_color_sensor', 'c1', 'D'),
  setupBlock('mp_setup_ultrasonic_sensor', 'u1', 'E'),
  setupBlock('mp_setup_force_sensor', 'f1', 'F'),
];

function workspaceState(devices: State[], program: State[], variables: State[] = []): State {
  const devicesChain = chain(devices);
  const programChain = chain(program);
  return {
    variables: [...DEVICE_VARIABLES, ...variables],
    blocks: {
      languageVersion: 0,
      blocks: [
        {
          type: 'mp_setup',
          x: 0,
          y: 0,
          ...(devicesChain ? { inputs: { DEVICES: { block: devicesChain } } } : {}),
        },
        {
          type: 'mp_program',
          x: 0,
          y: 200,
          ...(programChain ? { next: { block: programChain } } : {}),
        },
      ],
    },
  };
}

function generate(state: State) {
  const workspace = new Blockly.Workspace();
  try {
    loadWorkspace(workspace, state);
    return generateProgram(workspace);
  } finally {
    workspace.dispose();
  }
}

async function expectCompiles(code: string) {
  const outcome = await compilePython(code);
  expect(
    outcome.ok,
    outcome.ok ? '' : `${outcome.error.message} (line ${outcome.error.line})\n${code}`,
  ).toBe(true);
}

