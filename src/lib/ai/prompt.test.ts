import { describe, expect, it } from 'vitest';
import { blockReference, buildRequest, numbered, requestText, systemPrompt } from './prompt';

const FILES = [
  { name: 'setup.py', code: 'from pybricks.parameters import Port\n' },
  { name: 'main.py', code: '# Generated by MatPilot from blocks.\nrobot.straight(200)\n' },
];

const input = {
  mode: 'review' as const,
  files: FILES,
  openFile: 'main.py',
  tab: 'main',
  question: '',
  language: 'auto' as const,
  fallbackLanguage: 'th' as const,
};

describe('the AI request', () => {
  it('keeps the fixed instructions the same for every question and mode', () => {
    const a = buildRequest(input);
    const b = buildRequest({ ...input, mode: 'explain', question: 'What is line 2?' });
    expect(a.system).toBe(b.system);
    expect(a.system).toBe(systemPrompt());
  });

  it('sets the safety rules for children first', () => {
    const system = systemPrompt();
    expect(system).toMatch(/Only this robot, its program, and programming ideas/);
    expect(system).toMatch(/Never ask for personal information/);
    expect(system).toMatch(/Never pretend to be a person/);
    expect(system).toMatch(/Do not write a new program and do not give the finished fix/);
  });

  it('names the blocks, from the editor’s own word list', () => {
    const reference = blockReference();
    expect(reference).toContain('robot.straight(200) → block “move forward for … mm”');
    expect(reference).toContain('wait(1000)');
    // Each example once.
    const examples = `\n${reference}`
      .split('\n- ')
      .slice(1)
      .map((entry) => entry.split(' → ')[0]);
    expect(examples.length).toBeGreaterThan(60);
    expect(reference).not.toContain('motor_b');
    expect(new Set(examples).size).toBe(examples.length);
    // The fixed part stays a reasonable size (about 4 characters per token).
    expect(systemPrompt().length).toBeLessThan(40_000);
  });

  it('puts the open file first with numbered lines, then the task, the question and the language', () => {
    const request = buildRequest({ ...input, question: '  Why does it not stop?  ' });
    const user = request.user;
    expect(user.indexOf('=== main.py (the open tab) ===')).toBeLessThan(
      user.indexOf('=== setup.py ==='),
    );
    expect(user).toContain('  2| robot.straight(200)');
    expect(user.indexOf('THE TASK')).toBeLessThan(user.indexOf("THE CHILD'S QUESTION"));
    expect(user).toContain("THE CHILD'S QUESTION\nWhy does it not stop?");
    expect(user.endsWith("Answer in the language of the child's question.")).toBe(true);
  });

  it('answers in the browser’s language when there is no question, or as set', () => {
    expect(buildRequest(input).user).toContain('(No question: review the whole open file.)');
    expect(buildRequest(input).user.endsWith('Answer in Thai.')).toBe(true);
    expect(
      buildRequest({ ...input, language: 'en', question: 'ทำอะไร' }).user.endsWith(
        'Answer in English.',
      ),
    ).toBe(true);
  });

  it('shows the child exactly what is sent', () => {
    const request = buildRequest(input);
    const text = requestText(request);
    expect(text).toContain(request.system);
    expect(text).toContain(request.user);
  });

  it('numbers lines like an editor', () => {
    expect(numbered('a\nb\n')).toBe('  1| a\n  2| b');
    expect(numbered(Array.from({ length: 10 }, () => 'x').join('\n')).split('\n')[9]).toBe(
      '  10| x',
    );
  });
});
